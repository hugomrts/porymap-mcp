"""Tests for ``porymap_mcp.parsers.projectconfig``.

Format spec is in the module docstring; this file pins concrete examples
that match what Porymap actually writes for a pokeemerald-expansion project.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from porymap_mcp.errors import FormatError, ProjectError, UnsupportedBaseGameError
from porymap_mcp.parsers import projectconfig
from porymap_mcp.parsers.projectconfig import BaseGameVersion

# A minimal but realistic emerald-expansion-flavoured cfg: emerald base game with
# explicit mask overrides matching expansion's quad-byte attribute format.
EXPANSION_CFG = """\
# generated by Porymap
base_game_version = pokeemerald
use_poryscript = 1
use_custom_border_size = 0
default_map_width = 20
default_map_height = 20
default_primary_tileset = gTileset_General
default_secondary_tileset = gTileset_PalletTown
enable_triple_layer_metatiles = 0
block_metatile_id_mask = 0x03FF
block_collision_mask = 0x0C00
block_elevation_mask = 0xF000
metatile_attributes_size = 4
metatile_behavior_mask = 0x000001FF
metatile_terrain_type_mask = 0x00003E00
metatile_encounter_type_mask = 0x07000000
metatile_layer_type_mask = 0x60000000
path/data_map_folders = data/maps/
path/tilesets_folders = data/tilesets/
prefabs_filepath = prefabs.json
"""


class TestParseHappyPath:
    def test_extracts_base_game_version(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert config.base_game_version is BaseGameVersion.POKEEMERALD

    def test_extracts_expansion_attribute_overrides(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        # These are the values that distinguish expansion from vanilla emerald.
        assert config.metatile_attributes_size == 4
        assert config.behavior_mask == 0x000001FF
        assert config.terrain_type_mask == 0x00003E00
        assert config.encounter_type_mask == 0x07000000
        assert config.layer_type_mask == 0x60000000

    def test_layout_masks(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert config.metatile_id_mask == 0x03FF
        assert config.collision_mask == 0x0C00
        assert config.elevation_mask == 0xF000

    def test_booleans(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert config.use_poryscript is True
        assert config.use_custom_border_size is False
        assert config.triple_layer_metatiles is False

    def test_path_overrides_captured_separately(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert dict(config.paths) == {
            "path/data_map_folders": "data/maps/",
            "path/tilesets_folders": "data/tilesets/",
        }

    def test_prefabs_filepath(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert config.prefabs_filepath == "prefabs.json"

    def test_no_unknown_keys_when_all_known(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert dict(config.unknown_keys) == {}


class TestParseDefaults:
    def test_minimal_cfg_uses_emerald_defaults(self) -> None:
        config = projectconfig.parse("base_game_version = pokeemerald\n")
        # Layout masks default to the canonical Gen-3 packing.
        assert config.metatile_id_mask == 0x03FF
        assert config.collision_mask == 0x0C00
        assert config.elevation_mask == 0xF000
        # Vanilla emerald has 2-byte attributes (not expansion's 4).
        assert config.metatile_attributes_size == 2
        assert config.behavior_mask == 0x00FF
        # Booleans default to False, default map size to 20x20.
        assert config.use_poryscript is False
        assert config.default_map_width == 20
        assert config.default_map_height == 20
        # Default tilesets fall back to the Porymap-emerald defaults.
        assert config.default_primary_tileset == "gTileset_General"
        assert config.default_secondary_tileset == "gTileset_PalletTown"
        assert config.prefabs_filepath is None


class TestParseSyntax:
    def test_strips_inline_comments(self) -> None:
        cfg = "base_game_version = pokeemerald  # explanatory comment\n"
        config = projectconfig.parse(cfg)
        assert config.base_game_version is BaseGameVersion.POKEEMERALD

    def test_strips_full_line_comments(self) -> None:
        cfg = "# header comment\n\nbase_game_version = pokeemerald\n# trailing comment\n"
        config = projectconfig.parse(cfg)
        assert config.base_game_version is BaseGameVersion.POKEEMERALD

    def test_tolerates_extra_whitespace(self) -> None:
        cfg = "   base_game_version    =    pokeemerald   \n"
        config = projectconfig.parse(cfg)
        assert config.base_game_version is BaseGameVersion.POKEEMERALD

    def test_duplicate_key_last_wins(self) -> None:
        cfg = "base_game_version = pokeemerald\ndefault_map_width = 10\ndefault_map_width = 32\n"
        config = projectconfig.parse(cfg)
        assert config.default_map_width == 32

    def test_decimal_or_hex_integers(self) -> None:
        cfg = (
            "base_game_version = pokeemerald\n"
            "default_map_width = 30\n"
            "block_metatile_id_mask = 0x01FF\n"
        )
        config = projectconfig.parse(cfg)
        assert config.default_map_width == 30
        assert config.metatile_id_mask == 0x01FF

    def test_malformed_line_raises_format_error(self) -> None:
        cfg = "base_game_version = pokeemerald\nthis is not a key value pair\n"
        with pytest.raises(FormatError, match="line 2"):
            projectconfig.parse(cfg)

    def test_malformed_int_raises_format_error(self) -> None:
        cfg = "base_game_version = pokeemerald\ndefault_map_width = not-a-number\n"
        with pytest.raises(FormatError, match="default_map_width"):
            projectconfig.parse(cfg)

    def test_malformed_bool_raises_format_error(self) -> None:
        cfg = "base_game_version = pokeemerald\nuse_poryscript = true\n"
        with pytest.raises(FormatError, match="use_poryscript"):
            projectconfig.parse(cfg)


class TestParseBaseGameVersionGate:
    def test_missing_base_game_version_raises(self) -> None:
        with pytest.raises(UnsupportedBaseGameError) as exc_info:
            projectconfig.parse("default_map_width = 20\n")
        assert exc_info.value.declared == "<missing>"

    def test_unknown_base_game_version_raises(self) -> None:
        with pytest.raises(UnsupportedBaseGameError) as exc_info:
            projectconfig.parse("base_game_version = pokemystery\n")
        assert exc_info.value.declared == "pokemystery"
        assert set(exc_info.value.supported) == {"pokeruby", "pokefirered", "pokeemerald"}

    def test_known_but_unimplemented_version_raises(self) -> None:
        # pokeruby is a valid Porymap value, but its defaults table is not yet
        # populated. Parser raises with the *implemented* versions in supported.
        with pytest.raises(UnsupportedBaseGameError) as exc_info:
            projectconfig.parse("base_game_version = pokeruby\n")
        assert exc_info.value.declared == "pokeruby"
        assert set(exc_info.value.supported) == {"pokeemerald"}


class TestUnknownKeysRoundTrip:
    def test_unknown_keys_preserved(self) -> None:
        cfg = "base_game_version = pokeemerald\nexperimental_flag = 1\nfuture_feature = hello\n"
        config = projectconfig.parse(cfg)
        assert dict(config.unknown_keys) == {
            "experimental_flag": "1",
            "future_feature": "hello",
        }

    def test_ident_overrides_preserved(self) -> None:
        cfg = (
            "base_game_version = pokeemerald\n"
            "ident/symbol_obj_event_gfx_pointers = gObjectEventGraphicsInfoPointers\n"
        )
        config = projectconfig.parse(cfg)
        assert dict(config.idents) == {
            "ident/symbol_obj_event_gfx_pointers": "gObjectEventGraphicsInfoPointers",
        }


class TestSerialize:
    def test_round_trip_preserves_known_keys(self) -> None:
        original = projectconfig.parse(EXPANSION_CFG)
        serialized = projectconfig.serialize(original)
        reparsed = projectconfig.parse(serialized)
        assert reparsed == original

    def test_serialize_emits_alphabetical_order(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        text = projectconfig.serialize(config)
        keys = [line.split(" = ", 1)[0] for line in text.strip().splitlines()]
        assert keys == sorted(keys)

    def test_serialize_emits_trailing_newline(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        assert projectconfig.serialize(config).endswith("\n")

    def test_serialize_masks_in_hex(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        text = projectconfig.serialize(config)
        assert "block_metatile_id_mask = 0x3FF" in text
        assert "metatile_behavior_mask = 0x1FF" in text

    def test_serialize_booleans_as_0_or_1(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        text = projectconfig.serialize(config)
        assert "use_poryscript = 1" in text
        assert "use_custom_border_size = 0" in text

    def test_unknown_keys_round_trip_through_serialize(self) -> None:
        cfg = (
            "base_game_version = pokeemerald\n"
            "custom_extension = magic\n"
            "path/data_map_folders = data/maps/\n"
            "ident/symbol_foo = gFoo\n"
        )
        config = projectconfig.parse(cfg)
        reparsed = projectconfig.parse(projectconfig.serialize(config))
        assert dict(reparsed.unknown_keys) == {"custom_extension": "magic"}
        assert dict(reparsed.paths) == {"path/data_map_folders": "data/maps/"}
        assert dict(reparsed.idents) == {"ident/symbol_foo": "gFoo"}


class TestReadFromDisk:
    def test_reads_cfg_file(self, tmp_path: Path) -> None:
        cfg_path = tmp_path / "porymap.project.cfg"
        cfg_path.write_text(EXPANSION_CFG, encoding="utf-8")
        config = projectconfig.read(cfg_path)
        assert config.base_game_version is BaseGameVersion.POKEEMERALD

    def test_missing_file_raises_project_error(self, tmp_path: Path) -> None:
        with pytest.raises(ProjectError, match=r"porymap\.project\.cfg not found"):
            projectconfig.read(tmp_path / "porymap.project.cfg")


class TestWriteToDisk:
    def test_atomic_write_then_read_round_trip(self, tmp_path: Path) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        out = tmp_path / "porymap.project.cfg"
        projectconfig.write(config, out)
        # File materialized at the expected path
        assert out.is_file()
        # And reads back to an equal config
        assert projectconfig.read(out) == config


class TestImmutability:
    def test_project_config_is_frozen(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        with pytest.raises(AttributeError):
            config.metatile_id_mask = 0  # type: ignore[misc]

    def test_mapping_views_are_not_mutable(self) -> None:
        config = projectconfig.parse(EXPANSION_CFG)
        with pytest.raises(TypeError):
            config.paths["new"] = "x"  # type: ignore[index]
